// Generates web CSS/JS and Flutter Dart tokens from tokens.json.
// Usage: node design-tokens/build.js
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const DEFAULTS = {
  cssPath: path.join(ROOT, 'web/src/design/tokens.css'),
  jsPath: path.join(ROOT, 'web/src/design/tokens.js'),
  dartPath: path.join(ROOT, 'mobile/lib/core/theme/app_tokens.g.dart'),
};

function loadTokens() {
  return JSON.parse(fs.readFileSync(path.join(__dirname, 'tokens.json'), 'utf8'));
}

const hexToRgb = (hex) => {
  const h = hex.replace('#', '');
  return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16));
};

// Returns { hex, rgb, alpha } for a semantic or brand/functional token name.
function resolveColor(tokens, name) {
  const sem = tokens.color.semantic[name];
  let ref = name;
  let alpha = 1;
  if (sem) {
    ref = sem.ref;
    alpha = sem.alpha === undefined ? 1 : sem.alpha;
  }
  const [group, key] = ref.split('.');
  const hex = tokens.color[group] && tokens.color[group][key];
  if (!hex) throw new Error(`Unknown colour token: ${name}`);
  return { hex, rgb: hexToRgb(hex), alpha };
}

const channel = (c) => {
  const s = c / 255;
  return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
};
const luminance = ([r, g, b]) => 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b);
const blend = (fg, bg) => fg.rgb.map((c, i) => c * fg.alpha + bg[i] * (1 - fg.alpha));

// WCAG contrast; a translucent foreground/background is composited over white first.
function contrast(fg, bg) {
  const white = [255, 255, 255];
  const bgRgb = blend(bg, white);
  const fgRgb = blend(fg, bgRgb);
  const [a, b] = [luminance(fgRgb), luminance(bgRgb)].sort((x, y) => y - x);
  return (a + 0.05) / (b + 0.05);
}

const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
const camel = (...parts) => parts.map((p, i) => (i === 0 ? p : p[0].toUpperCase() + p.slice(1))).join('');
const cssColor = ({ hex, rgb, alpha }) => (alpha === 1 ? hex : `rgba(${rgb.join(', ')}, ${alpha})`);
const dartColor = ({ hex, alpha }) => {
  const a = Math.round(alpha * 255).toString(16).toUpperCase().padStart(2, '0');
  return `Color(0x${a}${hex.replace('#', '').toUpperCase()})`;
};

function collect(tokens) {
  const colors = [];
  for (const group of ['brand', 'functional']) {
    for (const key of Object.keys(tokens.color[group])) colors.push([camel(group, key), resolveColor(tokens, `${group}.${key}`)]);
  }
  for (const key of Object.keys(tokens.color.semantic)) colors.push([key, resolveColor(tokens, key)]);
  const numbers = [];
  for (const group of ['text', 'space', 'radius', 'size']) {
    for (const [k, v] of Object.entries(tokens[group])) numbers.push([group, k, v]);
  }
  return { colors, numbers };
}

function build(paths = DEFAULTS) {
  const tokens = loadTokens();
  const { colors, numbers } = collect(tokens);
  const banner = 'GENERATED by design-tokens/build.js from tokens.json. Do not edit.';

  const css = [`/* ${banner} */`, ':root {'];
  for (const [name, c] of colors) css.push(`  --color-${kebab(name)}: ${cssColor(c)};`);
  for (const [g, k, v] of numbers) css.push(`  --${g}-${kebab(k)}: ${v}px;`);
  css.push(`  --font-family: ${tokens.font.familyWeb || tokens.font.family};`);
  for (const [k, v] of Object.entries(tokens.font)) if (k.startsWith('weight')) css.push(`  --font-${kebab(k)}: ${v};`);
  for (const [k, v] of Object.entries(tokens.lineHeight)) css.push(`  --line-height-${k}: ${v};`);
  for (const [k, v] of Object.entries(tokens.letterSpacing || {})) css.push(`  --letter-spacing-${k}: ${v};`);
  for (const [k, v] of Object.entries(tokens.shadow || {})) css.push(`  --shadow-${k}: ${v};`);
  css.push('}', '');

  const jsObj = { color: Object.fromEntries(colors.map(([n, c]) => [n, cssColor(c)])), font: tokens.font, lineHeight: tokens.lineHeight };
  for (const g of ['text', 'space', 'radius', 'size']) jsObj[g] = tokens[g];
  const js = `// ${banner}\nexport const tokens = ${JSON.stringify(jsObj, null, 2)};\nexport const color = tokens.color;\n`;
  const flatColors = Object.fromEntries(colors.map(([n, c]) => [n, cssColor(c)]));
  const jsWithFlat = `${js}export const flat = ${JSON.stringify(flatColors, null, 2)};\n`;

  const dart = [`// ${banner}`, "import 'package:flutter/painting.dart';", '', 'abstract final class AppTokens {'];
  for (const [name, c] of colors) dart.push(`  static const Color ${name} = ${dartColor(c)};`);
  for (const [g, k, v] of numbers) dart.push(`  static const double ${camel(g, /^\d/.test(k) ? `s${k}` : k)} = ${v};`);
  dart.push(`  static const String fontFamily = '${tokens.font.familyName}';`);
  dart.push(`  static const double lineHeightBody = ${tokens.lineHeight.body};`);
  dart.push(`  static const double lineHeightHeading = ${tokens.lineHeight.heading};`);
  dart.push('}', '');

  for (const [p, content] of [[paths.cssPath, css.join('\n')], [paths.jsPath, jsWithFlat], [paths.dartPath, dart.join('\n')]]) {
    fs.mkdirSync(path.dirname(p), { recursive: true });
    fs.writeFileSync(p, content);
  }
  return paths;
}

module.exports = { loadTokens, resolveColor, contrast, build };

if (require.main === module) {
  const p = build();
  console.log(`tokens written:\n  ${p.cssPath}\n  ${p.jsPath}\n  ${p.dartPath}`);
}
